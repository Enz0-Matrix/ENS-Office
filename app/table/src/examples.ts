export function exampleFor(fn: string): FunctionExample | undefined {
  const name = fn.toUpperCase();
  return EXAMPLES.find((e) => e.fn === name || (e.fn === 'ИНДЕКС' && name === 'ПОИСКПОЗ') || (e.fn === 'СЦЕП' && name === 'СЦЕПИТЬ'));
}
